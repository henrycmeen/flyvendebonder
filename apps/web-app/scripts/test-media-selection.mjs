import assert from "node:assert/strict";
import { build } from "esbuild";

const bundle = await build({ entryPoints: ["src/lib/media-selection.ts"], bundle: true, format: "esm", platform: "browser", write: false });
const { stageMedia, fromPickedFiles, collectDroppedEntries, extractDroppedMedia } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`);
const file = (name, size = 12, extra = {}) => ({ name, size, type: "", lastModified: 42, ...extra });
const selection = (name, relativePath = null, size = 12) => ({ file: file(name, size), relativePath });
const initial = stageMedia([], [selection("a.JPG"), selection("a.JPG"), selection("empty.tif", null, 0), selection("video.mp4"), selection("a.JPG", "other/a.JPG")]);
assert.equal(initial.items.length, 2);
assert.equal(initial.added, 2);
assert.equal(initial.duplicates, 1);
assert.equal(initial.empty, 1);
assert.equal(initial.unsupported, 1);
assert.equal(stageMedia(initial.items, [selection("a.JPG")]).duplicates, 1);
assert.equal(stageMedia([], [{ file: file("fake.png", 12, { type: "image/jpeg" }), relativePath: null }]).unsupported, 1);
assert.equal(stageMedia([], [{ file: file("extensionless", 12, { type: "image/jpeg" }), relativePath: null }]).unsupported, 1);
assert.equal(fromPickedFiles([file("a.tiff", 12, { webkitRelativePath: "Flight/Nested/a.tiff" })])[0].relativePath, "Flight/Nested/a.tiff");
const entryFile = (name, fullPath) => ({ name, fullPath, isFile: true, file: (resolve) => resolve(file(name)) });
let reads = 0;
const nested = { name: "Nested", isDirectory: true, createReader: () => ({ readEntries: (resolve) => resolve(reads++ === 0 ? [entryFile("a.tiff")] : []) }) };
let rootReads = 0;
const root = { name: "Flight", isDirectory: true, createReader: () => ({ readEntries: (resolve) => resolve(rootReads++ === 0 ? [nested] : rootReads === 2 ? [entryFile("b.jpg")] : []) }) };
const collected = await collectDroppedEntries([root]);
assert.deepEqual(collected.files.map((item) => item.relativePath), ["Flight/Nested/a.tiff", "Flight/b.jpg"]);
assert.deepEqual(collected.errors, []);
let failingReads = 0;
const broken = { name: "Broken", isDirectory: true, createReader: () => ({ readEntries: (resolve, reject) => failingReads++ === 0 ? resolve([entryFile("good.jpg")]) : reject(new Error("unreadable")) }) };
const partial = await collectDroppedEntries([broken, { name: "bad.jpg", isFile: true, file: (_, reject) => reject(new Error("denied")) }]);
assert.equal(partial.files[0].relativePath, "Broken/good.jpg");
assert.deepEqual(partial.errors, ["Broken", "bad.jpg"]);
const mixed = await extractDroppedMedia({ items: [{ kind: "file", webkitGetAsEntry: () => entryFile("dir.jpg", "/Flight/dir.jpg") }, { kind: "file", getAsFile: () => file("fallback.jpg") }, { kind: "file", getAsFile: () => null }], files: [] });
assert.deepEqual(mixed.files.map((item) => item.relativePath), ["Flight/dir.jpg", null]);
assert.equal(mixed.errors.length, 1);
console.log("media-selection tests passed");
